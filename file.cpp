// ============================================================
//  并查集（Disjoint Set Union，简称 DSU）
//  作者：一个刚学懂的大一学生（没错就是我哈哈）
//
//  说明：这份代码给"每一行"都写了注释，方便复习！
//
//  它到底是干嘛的？一句话：管"集合"的！
//  就干三件事：
//    1. 初始化 init()  —— 一开始每个人各自成团
//    2. 合并   union() —— 让两个集合变成一家人
//    3. 查找   find()  —— 查某个节点属于哪个团
//  哦对，还有个经常问的：a 和 b 是不是一家人？
//  那就是 find(a) == find(b)，本质还是在查找
//
//  最经典的比喻就是：查"祖宗"！
//  每个集合 = 一棵树，树根 = 老大（代表节点）
//  只要大家的老大是同一个，那大家就是一家人！
//
//  我学的两种优化（巨重要）：
//  ① 路径压缩：find 的时候，顺手把沿途的节点全挂到根底下
//             （不然树会越长越歪，退化成一条链，慢到哭）
//  ② 按秩合并：合并的时候，让矮树挂到高树下面
//             （跟"矮个子别逞强去顶天"一个道理）
//  两个加起来，单次操作几乎就是 O(1) 级别，快得离谱！
// ============================================================

// ============ 头文件区 ============
#include <iostream>                  // iostream：负责"输入输出"，没有它程序就没法用 cout 打印东西
#include <vector>                    // vector：动态数组（可变长数组），我们用它来存 parent 和 rank
#include <algorithm>                 // algorithm：算法库，里面有 sort（排序）函数，应用4 会用到
using namespace std;                 // 声明使用标准命名空间，这样写 cout 就不用写 std::cout 了

// ============ 并查集类的定义 ============
class UnionFind {                    // 定义一个"并查集"类，把并查集的所有操作都封装在里面
private:                             // private 私有区：下面的成员变量只有类内部能用，外面不能直接改
    vector<int> parent;              // parent[i] = i 的"爸爸"是谁；爸爸是自己就说明 i 是老大（根节点）
    vector<int> rank;                // rank[i] = 以 i 为根的那棵树的"高度"，用于按秩合并优化
    int count;                       // count = 当前一共有多少个集合（也叫连通块）

public:                              // public 公有区：下面的函数是给外面调用的"接口"
    // ---------- 1) 初始化 ----------
    UnionFind(int n) {               // 构造函数：new UnionFind(n) 时自动执行，n = 元素个数
        parent.resize(n);            // 把 parent 数组的长度设置为 n（开出 n 个格子）
        rank.resize(n, 1);           // 把 rank 数组长度设为 n，每个格子初始值 = 1（单棵树高度是 1）
        count = n;                   // 一开始 n 个人互不认识，所以一共有 n 个集合
        for (int i = 0; i < n; i++) { // for 循环：让 i 从 0 跑到 n-1，把每个元素都处理一遍
            parent[i] = i;           // 关键一步：每个人的爸爸就是自己 => 代表"每个人都是自己的老大"
        }                            // 循环体结束
    }                                // 构造函数结束

    // ---------- 2) 查找 ----------
    int find(int x) {                // find(x)：查找 x 所在集合的"老大"（根节点），返回老大的编号
        if (parent[x] != x) {        // 如果 x 的爸爸不是自己 => 说明 x 不是老大，上面还有人
            parent[x] = find(parent[x]); // 路径压缩：递归向上找"爸爸的爸爸..."直到根，
                                         // 找到后直接把 x 挂到根下面，下次再查找就超快
        }                            // if 语句结束
        return parent[x];            // 返回 x 的老大（如果 x 就是老大，就返回 x 自己）
    }                                // find 函数结束

    bool isConnected(int a, int b) { // isConnected(a,b)：判断 a 和 b 是否在同一个集合
        return find(a) == find(b);   // 两人的老大相同 => 一家人，返回 true；否则返回 false
    }                                // isConnected 函数结束

    // ---------- 3) 合并 ----------
    void unionSets(int x, int y) {   // unionSets(x,y)：把 x 和 y 所在的两个集合合并成一个大集合
        int rx = find(x);            // 先查出 x 的老大，记作 rx（x 所在集合的代表）
        int ry = find(y);            // 再查出 y 的老大，记作 ry（y 所在集合的代表）
        if (rx == ry) return;        // 如果老大相同 => 本来就是一家人，直接结束，不用合并
        // 下面就是"按秩合并"优化：让矮树认高树当爸爸，防止树越长越高
        if (rank[rx] < rank[ry]) {   // 情况1：rx 那棵树比 ry 矮
            parent[rx] = ry;         // 让 rx（矮）认 ry（高）当爸爸 => 矮树挂到高树下
        } else if (rank[rx] > rank[ry]) { // 情况2：rx 那棵树比 ry 高
            parent[ry] = rx;         // 反过来，让 ry（矮）认 rx（高）当爸爸
        } else {                     // 情况3：两棵树一样高
            parent[ry] = rx;         // 谁当爸爸都行，这里让 ry 认 rx 当爸爸
            rank[rx]++;              // 但两棵一样高的树合并后，新树高度 +1，要更新 rank
        }                            // 按秩合并的 if-else 结束
        count--;                     // 两个集合合并成一个，集合总数减 1
    }                                // unionSets 函数结束

    int getCount() {                 // getCount()：对外提供"现在有几个集合"的接口
        return count;                // 把私有成员 count 的值返回给调用者
    }                                // getCount 函数结束

    // ---------- 4) 展示每个集合里的元素（新增功能！）----------
    void printSets() {               // printSets()：把"每个集合里都有哪些元素"打印出来
        // 思路：用"老大"当分组依据，把每个元素放进它老大对应的组
        vector<vector<int>> groups(parent.size()); // 建一个二维动态数组：groups[r] 存"老大是 r"的所有元素
        for (int i = 0; i < (int)parent.size(); i++) { // 遍历每一个元素 i
            int root = find(i);      // 先找到 i 的老大（根节点）是谁
            groups[root].push_back(i); // 把 i 塞进它老大对应的小组
        }                            // 循环结束：现在所有元素都分好组了
        for (int r = 0; r < (int)groups.size(); r++) { // 再遍历每个可能的"老大"编号 r
            if (groups[r].empty()) continue; // 如果这个组是空的（没人以 r 为老大），跳过不看
            cout << "集合{老大=" << r << "}: "; // 打印组名，告诉大家这个集合的老大是谁
            for (int e : groups[r]) { // 遍历这个组里的每一个元素
                cout << e << " ";     // 把元素打印出来，中间用空格隔开
            }                         // 内层循环结束
            cout << endl;             // 打完整组后换行
        }                             // 外层循环结束
    }                                 // printSets 函数结束
};                                   // 类定义结束（结尾的 ; 绝对不能丢！）

// ============ 主函数：程序从这里开始 ============
int main() {                         // main 函数：整个程序的入口，代码从上往下依次执行
    // ---------- 应用 1：基础玩法（初始化 + 合并 + 查找）----------
    cout << "========== 应用1：基础的合并和查找 ==========" << endl; // cout 打印一行提示语，endl = 换行
    UnionFind uf(6);                 // 创建并查集对象 uf，里面有 6 个人（编号 0~5）
    uf.unionSets(0, 1);              // 调用合并：0 和 1 结拜，变成一家人
    uf.unionSets(1, 2);              // 调用合并：1 又和 2 结拜 => 现在 0、1、2 是一伙的
    uf.unionSets(3, 4);              // 调用合并：3 和 4 结拜，变成一家人

    cout << "0 和 2 是一伙的吗？" << (uf.isConnected(0, 2) ? "是！" : "不是") << endl; // 判断 0 和 2 是否同集合，会输出"是！"
    cout << "0 和 3 是一伙的吗？" << (uf.isConnected(0, 3) ? "是！" : "不是") << endl; // 判断 0 和 3 是否同集合，会输出"不是"
    cout << "0 的团伙老大是：" << uf.find(0) << endl; // 打印 0 的老大（根节点）是谁
    cout << "现在一共几伙人？" << uf.getCount() << endl; // 打印集合总数，应该是 3 伙：{0,1,2} {3,4} {5}
    cout << "每伙人都有谁呢？看看集合里的元素：" << endl; // 新增：提示下面要看集合元素了
    uf.printSets();                  // 新增：调用 printSets，把每个集合里的元素都打印出来
    cout << endl;                    // 输出一个空行，让输出排版好看一点

    // ---------- 应用 2：统计"省份"数量（LeetCode 547 的思路）----------
    // 给你一张 n*n 的矩阵，graph[i][j] == 1 表示 i 和 j 直接相连
    // 问有几个"连通块"（相当于几伙人）
    cout << "========== 应用2：统计连通块个数（省份数量） ==========" << endl; // 打印提示语
    int n = 4;                       // 定义变量 n = 4，表示有 4 个城市（编号 0~3）
    // 城市 0-1 相连，1-2 相连，3 自己玩
    int graph[4][4] = {              // 定义一个 4x4 的二维数组，存城市之间的"相连关系"
        {1, 1, 0, 0},                // 第 0 行：城市 0 和 0、1 相连
        {1, 1, 1, 0},                // 第 1 行：城市 1 和 0、1、2 相连
        {0, 1, 1, 0},                // 第 2 行：城市 2 和 1、2 相连
        {0, 0, 0, 1}                 // 第 3 行：城市 3 只和自己相连
    };
    UnionFind province(n);           // 创建并查集对象 province，来处理这 n 个城市
    for (int i = 0; i < n; i++) {    // 外层循环：i 从 0 到 n-1，遍历每一行
        for (int j = i + 1; j < n; j++) { // 内层循环：j 从 i+1 开始，只扫矩阵上半部分（对称矩阵）
            if (graph[i][j] == 1) {  // 如果城市 i 和 j 直接相连（值为 1）
                province.unionSets(i, j); // 就用并查集把 i 和 j 合并成一伙
            }                        // if 结束
        }                            // 内层循环结束
    }                                // 外层循环结束
    cout << "这 " << n << " 个城市一共分成 " << province.getCount() << " 个省份" << endl; // 打印省份（连通块）个数
    cout << "每个省份里都有哪些城市：" << endl; // 新增：提示语
    province.printSets();            // 新增：把每个省份（集合）里的城市都打印出来
    cout << endl;                    // 输出空行

    // ---------- 应用 3：判断图里有没有环 ----------
    // 关键点：一条边连上两个"已经是一家人"的节点 => 有环！
    cout << "========== 应用3：无向图判环 ==========" << endl; // 打印提示语
    UnionFind cycleCheck(4);         // 创建并查集对象 cycleCheck，处理 4 个点
    // 边：0-1, 1-2, 2-0（这样就有环了）, 2-3
    int edges[][2] = {{0, 1}, {1, 2}, {2, 0}, {2, 3}}; // 用二维数组存所有边，每条边是 {起点, 终点}
    bool hasCycle = false;           // 布尔变量记录"有没有环"，初始为 false（还没有）
    for (auto &e : edges) {          // 范围 for 循环：依次拿出每条边 e（auto 让编译器自动推断类型）
        if (cycleCheck.isConnected(e[0], e[1])) { // 如果这条边的两个端点已经在同一个集合里
            hasCycle = true;         // 说明加这条边会形成环！把标志改成 true
            cout << "边 " << e[0] << "-" << e[1] << " 让图出现了环！" << endl; // 打印是哪条边造成的
        } else {                     // 否则（两个端点还不在同一个集合）
            cycleCheck.unionSets(e[0], e[1]); // 就放心把这条边加入：合并两个端点
        }                            // if-else 结束
    }                                // for 循环结束
    cout << (hasCycle ? "结论：图里有环！" : "结论：图里没有环") << endl; // 三目运算符：有环打印"有环"，没环打印"没环"
    cout << endl;                    // 输出空行

    // ---------- 应用 4：Kruskal 最小生成树（并查集最经典的应用！）----------
    cout << "========== 应用4：Kruskal 最小生成树 ==========" << endl; // 打印提示语
    // 每条边：{起点, 终点, 权值}
    vector<vector<int>> kEdges = {   // 用"二维动态数组"存所有边
        {0, 1, 10}, {0, 2, 6}, {0, 3, 5}, // 边1：0-1 权值10；边2：0-2 权值6；边3：0-3 权值5
        {1, 3, 15}, {2, 3, 4}        // 边4：1-3 权值15；边5：2-3 权值4
    };
    // 1) 先把所有边按权值从小到大排序（贪心：优先挑便宜的边）
    sort(kEdges.begin(), kEdges.end(), // 调用 sort 排序，排序范围是整个 kEdges
         [](const vector<int> &a, const vector<int> &b) { // 自定义比较规则（lambda 表达式，a 和 b 是两条边）
             return a[2] < b[2];      // 按每条边的第 3 个元素（下标 2，即权值）从小到大排
         });                          // 排序的 lambda 结束

    UnionFind mst(4);                 // 创建并查集对象 mst，处理 4 个点
    int totalWeight = 0;              // 变量 totalWeight 记录生成树的总权值，初始为 0
    cout << "选中的边：" << endl;      // 打印提示
    for (auto &e : kEdges) {          // 遍历排好序后的每一条边
        int u = e[0], v = e[1], w = e[2]; // 把边的三个元素取出来：起点 u、终点 v、权值 w
        if (!mst.isConnected(u, v)) { // 如果 u 和 v 还不在一家（加这条边不会成环）
            mst.unionSets(u, v);      // 放心收下这条边：把 u、v 合并进同一个集合
            totalWeight += w;         // 总权值累加这条边的权值
            cout << "  " << u << " - " << v << "（权值 " << w << "）" << endl; // 打印选中的这条边
        }                             // if 结束
        // 会成环的边直接跳过，这就是贪心！
    }                                 // for 循环结束
    cout << "最小生成树的总权值 = " << totalWeight << endl; // 打印最终算出来的总权值

    return 0;                        // 返回 0 表示程序正常结束
}                                    // main 函数结束
